#!/bin/bash
# Entrypoint of the ToyMayhem image. Usage: docker-entrypoint.sh AuthServer|MainServer|CastServer
#
# Writes Setup/config.ini from the environment, then replaces itself with the server (exec), so the server is the
# main process, gets the stop signal and its exit code is the container's exit code.
# Secrets never go into config.ini: it only holds the NAMES of the variables, and each NAME_FILE variable (set by the
# compose file) points at a file under /run/secrets. See Common/include/Utils/SecretSource.h.
set -euo pipefail

server="${1:-}"
case "$server" in
    AuthServer|MainServer|CastServer) ;;
    *) echo "[entrypoint] usage: $0 AuthServer|MainServer|CastServer (got '${server}')" >&2; exit 64 ;;
esac

# The three servers share one network namespace (see docker-compose.yml), so there is one IP for all of them.
# The servers bind to it and find each other through it.
: "${TM_APP_IP:?TM_APP_IP is not set}"
db_host="${TM_DB_HOST:-db}"
db_port="${TM_DB_PORT:-3306}"
db_name="${TM_DB_NAME:-microvolts-db}"
db_user="${TM_DB_USER:-mvapp}"
enhanced="${TM_ENHANCED_SECURITY:-true}"
origins="${TM_ALLOWED_ORIGINS:?TM_ALLOWED_ORIGINS is not set}"
client_version="${TM_CLIENT_VERSION:-0.0.3}"

for v in TM_APP_IP db_host db_port db_name db_user enhanced origins client_version \
         TM_SMTP_SERVER TM_EMAIL_SENDER TM_EMAIL_USERNAME TM_SECURITY_NOTIFY; do
    value="${!v:-}"
    # one line, no characters that could add a section or a key to the ini file
    if [[ "$value" == *$'\n'* || "$value" == *$'\r'* || "$value" == *'['* || "$value" == *']'* ]]; then
        echo "[entrypoint] $v contains a character that is not allowed in config.ini" >&2
        exit 64
    fi
done
case "$enhanced" in true|false) ;; *) echo "[entrypoint] TM_ENHANCED_SECURITY must be true or false" >&2; exit 64 ;; esac

# The server finds itself by the IP of the default route (Common/include/Utils/Utils.h getLocalIp). If the IP the
# compose file promised is not on this container, stop with a clear message instead of a sanity check failure.
if ! grep -q -- "|-- ${TM_APP_IP}\$" /proc/net/fib_trie 2>/dev/null; then
    echo "[entrypoint] ${TM_APP_IP} is not an address of this container (network_mode / ipv4_address wrong?)" >&2
    exit 78
fi

# Secrets: every one must be given as a file, and the file must exist, before the server starts
for f in MV_DB_PW_FILE MV_JWT_FILE MV_IPC_SECRET_FILE MV_PW_PEPPER_FILE; do
    path="${!f:-}"
    if [[ -z "$path" || ! -f "$path" || ! -s "$path" ]]; then
        echo "[entrypoint] $f is not set or does not point at a non-empty file" >&2
        exit 78
    fi
done
if [[ "$enhanced" == true ]]; then
    for f in MVEMAIL_SECRET_FILE MV2FA_SECRET_FILE MV_EMAIL_TOKEN_FILE; do
        path="${!f:-}"
        if [[ -z "$path" || ! -f "$path" || ! -s "$path" ]]; then
            echo "[entrypoint] $f is not set or does not point at a non-empty file (needed because TM_ENHANCED_SECURITY=true)" >&2
            exit 78
        fi
    done
fi

setup_dir=/app/emu/Setup
if [[ ! -w "$setup_dir" ]]; then
    echo "[entrypoint] $setup_dir is not writable: mount a tmpfs there for uid $(id -u)" >&2
    exit 78
fi

umask 0077
cat > "$setup_dir/config.ini" <<INI
# generated by docker-entrypoint.sh at start, do not edit
[AuthServer]
LocalIp = ${TM_APP_IP}
Ip = ${TM_APP_IP}
Port = 13000
GradedPort = 13001
VpnIp = ${TM_APP_IP}
EnhancedSecurity = ${enhanced}

[MainServer_1]
LocalIp = ${TM_APP_IP}
Ip = ${TM_APP_IP}
Port = 13005
IpcPort = 14005
IsPublic = true

[CastServer_1]
LocalIp = ${TM_APP_IP}
Ip = ${TM_APP_IP}
Port = 13006
IpcPort = 14006
IPC_EnableDeadBroadcast = true

[Database]
LocalIp = ${db_host}
Ip = ${db_host}
Port = ${db_port}
DatabaseName = ${db_name}
Username = ${db_user}
PasswordEnvironmentName = MV_DB_PW

[Website]
Ip = ${TM_APP_IP}
Port = 8080
JwtTokenEnvironmentName = MV_JWT
AllowedOrigins = ${origins}

[Ipc]
SecretEnvironmentName = MV_IPC_SECRET

[Client]
ClientVersion = ${client_version}

[General]
EmailSecret = MVEMAIL_SECRET
2faSecret = MV2FA_SECRET
PasswordPepper = MV_PW_PEPPER
PasswordPepperVersion = ${TM_PW_PEPPER_VERSION:-1}
SmtpServer = ${TM_SMTP_SERVER:-smtp://localhost:25}
EmailSender = ${TM_EMAIL_SENDER:-toymayhem@example.invalid}
EmailUsername = ${TM_EMAIL_USERNAME:-toymayhem@example.invalid}
EmailToken = MV_EMAIL_TOKEN
SecurityNotificationReceiver = ${TM_SECURITY_NOTIFY:-blue@example.invalid}
INI

mkdir -p "${TB_LOG_DIR:-/var/log/toymayhem}" 2>/dev/null || true
echo "[entrypoint] $(date -u '+%F %T') config.ini written for ${server} (ip ${TM_APP_IP}, database ${db_user}@${db_host}:${db_port}/${db_name}, enhanced security ${enhanced})"
cd /app/emu/Output
exec "./${server}.elf"
