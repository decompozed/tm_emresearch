"""The official team spawns of every map -> Common/include/HaveApi/PartySpawns.h (Hardpoint / Headquarters /
Domination, D87).

User 2026-10-03: "just use the official team-mode spawns, each team at its base, and make sure opposite teams don't
spawn in the same places". Per map, team_spawns.py: the TDM (else SAB) REDTEAM / BLUETEAM nodes the DLL loads into the
red / blue spawn lists, with a floor under them, none closer than APART to a node of the other team; at most SPAWNS per
team (the 0x38 message holds 8), spread out. The server sends each player its team's points; the DLL respawns at the
game's own entry at one of them.

Usage: python party_spawns.py <unpacked map.dat dir> <RoomEnums.h> <output .h>
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
from hardpoint_zones import floor_levels, triangles  # noqa: E402
from map_spawns import spawns as read_spawns  # noqa: E402
from team_spawns import spread, team_spawns  # noqa: E402

SPAWNS = 8


def map_points(folder):
    files = {f.lower(): os.path.join(folder, f) for f in os.listdir(folder)}
    if 'world.nif' not in files or 'world_colp.nif' not in files:
        return None
    teams = team_spawns(read_spawns(files['world.nif']), floor_levels(triangles(files['world_colp.nif'])))
    if teams is None:
        return None
    group, red, blue = teams
    return group, [(1, p) for p in spread(red, SPAWNS)] + [(2, p) for p in spread(blue, SPAWNS)]


def header(rows, license_text):
    out = license_text + """#ifndef COMMON_HAVE_API_PARTY_SPAWNS_H
#define COMMON_HAVE_API_PARTY_SPAWNS_H

#include <algorithm>
#include <array>
#include <cstdint>
#include <span>

// The official team spawns per map (Hardpoint / Headquarters / Domination, D87), generated by
// Tools/nif/party_spawns.py from map.dat: the TDM (else SAB) REDTEAM / BLUETEAM nodes of mapNNN/World.nif the DLL
// loads into the red / blue spawn lists, with a floor under them, none near a node of the other team, at most 8 per
// team. team: 1 red, 2 blue. The server sends each player its team's points (0x38).
namespace Common::HaveApi
{
	struct PartySpawn
	{
		std::uint16_t map;
		std::int8_t team;
		float x, y, z;
	};

	inline constexpr auto partySpawns = std::to_array<PartySpawn>({
"""
    for mid, name, group, points in rows:
        out += '\t\t// map%03d %s: %s, red %d, blue %d\n' % (mid, name, group, sum(1 for t, _ in points if t == 1),
                                                            sum(1 for t, _ in points if t == 2))
        for team, p in points:
            out += '\t\t{ %d, %d, %.1ff, %.1ff, %.1ff },\n' % (mid, team, p[0], p[1], p[2])
    out += """	});

	// The team spawns of `map` (contiguous in the table); empty for an unknown map.
	[[nodiscard]] inline std::span<const PartySpawn> findPartySpawns(std::uint32_t map)
	{
		const auto first = std::ranges::find(partySpawns, map, &PartySpawn::map);
		const auto last = std::find_if(first, partySpawns.end(), [&](const PartySpawn& s) { return s.map != map; });
		return std::span<const PartySpawn>{ first, last };
	}
}

#endif
"""
    return out


if __name__ == '__main__':
    root, enums, output = sys.argv[1:4]
    names = {int(n): v for n, v in re.findall(r'\{(\d+), "(\w+)"\}', open(enums).read())}
    rows = []
    for d in sorted(os.listdir(root)):
        if not re.fullmatch(r'map\d{3}', d):
            continue
        mid = int(d[3:])
        result = map_points(os.path.join(root, d))
        if result is None:
            print(mid, names.get(mid, d), 'no team spawns')
            continue
        group, points = result
        rows.append((mid, names.get(mid, d), group, points))
        print(mid, names.get(mid, d), group, 'red', sum(1 for t, _ in points if t == 1), 'blue', sum(1 for t, _ in points if t == 2))
    hp = os.path.join(os.path.dirname(output), 'HardpointZones.h')
    license_text = open(hp, encoding='utf-8').read().replace('\r\n', '\n').split('#ifndef')[0]
    open(output, 'w', encoding='utf-8', newline='').write(header(rows, license_text).replace('\n', '\r\n'))
    print('maps', len(rows))
