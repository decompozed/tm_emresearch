"""Lava Escape map bounds -> Common/include/HaveApi/LavaMaps.h.

For every map folder mapNNN of the unpacked map.dat: the world bounds of World_colb.nif (bullet collision: the whole
playable geometry), node transforms applied (nif.world_bounds). A map whose collision reaches beyond the lava models
(MODEL_HALF_SIZE: far-away scenery) gets the x / y bounds of its walkable floor instead (make_prop_models.playable_floor:
the floor connected to the spawn nodes and Hardpoint zone spots) + MARGIN. The server starts the lava floor / walls from them.
Map names from the emulator's map list (RoomEnums.h, the ToyBattles numbering).

Usage: python make_lava_maps.py <unpacked map.dat dir> <RoomEnums.h> <output .h>
"""
import os
import re
import sys

sys.path.insert(0, os.path.dirname(__file__))
import nif  # noqa: E402
from hardpoint_zones import CELL  # noqa: E402
from make_prop_models import playable_floor  # noqa: E402

MODEL_HALF_SIZE = 25000.0  # Common::HaveApi::lavaModelHalfSize: the lava models' reach
MARGIN = 1000.0

HEADER = """#ifndef COMMON_HAVE_API_LAVA_MAPS_H
#define COMMON_HAVE_API_LAVA_MAPS_H

#include <algorithm>
#include <array>
#include <cstdint>
#include <optional>

// World bounds of every map's collision mesh (map.dat: mapNNN/World_colb.nif, NNN = map id), generated by
// Tools/nif/make_lava_maps.py (node transforms applied to the POSITION streams). Units are the game's world units, the
// same the clients use in the positions (order 281, half floats) and that the DLL uses for the lava (0x23 / 0x24).
// See doc/have_api_lava_and_maps.md. A few entries include far-away geometry: the lava then starts wider, which only
// makes the walls take longer. Do not edit: regenerate.
namespace Common::HaveApi
{
	struct MapBounds
	{
		std::uint16_t map;
		float minX, maxX, minY, maxY, minZ, maxZ;
	};

	inline constexpr auto mapBounds = std::to_array<MapBounds>({
"""

FOOTER = """	});

	[[nodiscard]] inline std::optional<MapBounds> findMapBounds(std::uint32_t map)
	{
		const auto found = std::ranges::find(mapBounds, map, &MapBounds::map);
		return found != mapBounds.end() ? std::optional{ *found } : std::nullopt;
	}
}

#endif
"""


def main(root, enums, output):
    names = {int(n): v for n, v in re.findall(r'\{(\d+), "(\w+)"\}', open(enums, encoding='utf-8').read())}
    rows = []
    for d in sorted(os.listdir(root)):
        if not d.startswith('map') or d == 'mapObjects':
            continue
        files = {f.lower(): os.path.join(root, d, f) for f in os.listdir(os.path.join(root, d))}
        if 'world_colb.nif' not in files:
            continue
        count, lo, hi, _ = nif.world_bounds(files['world_colb.nif'])
        if not count:
            continue
        mid = int(d[3:])
        if max(abs(v) for v in lo[:2] + hi[:2]) > MODEL_HALF_SIZE:
            # far-away geometry (ToyBattles Summer Chess, Cargo O): x / y from the walkable floor instead
            floors, cells = playable_floor(files, mid)
            if cells:
                xs = [c[0] for c in floors]
                ys = [c[1] for c in floors]
                lo[0], hi[0] = min(xs) * CELL - MARGIN, (max(xs) + 1) * CELL + MARGIN
                lo[1], hi[1] = min(ys) * CELL - MARGIN, (max(ys) + 1) * CELL + MARGIN
                print(mid, 'collision too wide: bounds of the walkable floor')
        rows.append('\t\t{ %3d, %10.1ff, %10.1ff, %10.1ff, %10.1ff, %10.1ff, %10.1ff }, // %s (%d vertices)\n' % (
            mid, lo[0], hi[0], lo[1], hi[1], lo[2], hi[2], names.get(mid, d), count))
        print(mid, names.get(mid, d), [round(v) for v in lo], [round(v) for v in hi])
    license_text = open(output, encoding='utf-8').read().split('#ifndef')[0] if os.path.exists(output) else ''
    open(output, 'w', encoding='utf-8', newline='').write((license_text + HEADER + ''.join(rows) + FOOTER).replace('\n', '\r\n'))


if __name__ == '__main__':
    main(sys.argv[1], sys.argv[2], sys.argv[3])
